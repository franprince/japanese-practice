import { beforeAll, describe, expect, it } from 'bun:test'
import { existsSync, readFileSync } from 'node:fs'
import kuromoji from 'kuromoji'
import { convert, type Entry, type Lexicon } from '../lib/convert'
import { commonWords, kuromojiLexicon } from '../lib/lexicon'

// A tiny hand-made lexicon: costs decide the path, connection ids model grammar.
const NOUN = 1, PARTICLE = 2
const word = (surface: string, cost: number, id = NOUN, pos = '名詞', sub = '一般'): Entry => ({ surface, left: id, right: id, cost, pos, sub, base: surface })
const WORDS: Record<string, Entry[]> = {
  はし: [word('箸', 100), word('橋', 200), word('端', 300)],
  は: [word('は', 50, PARTICLE, '助詞', '係助詞'), word('歯', 400)],
  し: [word('死', 900)],
  を: [word('を', 50, PARTICLE, '助詞', '格助詞')],
  かんじ: [word('幹事', 100), word('漢字', 200)],
  ご: [word('五', 10, NOUN, '名詞', '数'), word('語', 500)],
}
const fake = (bonus: Record<string, number> = {}): Lexicon => ({
  lookup: (reading) => WORDS[reading] ?? [],
  connect: (right, left) => (right === NOUN && left === NOUN ? 1000 : 0),
  bonus: (entry) => bonus[entry.surface] ?? 0,
})

describe('convert', () => {
  it('splits kana into phrases, attaching particles to the word before them', () => {
    expect(convert('はしを', fake()).map((p) => p.reading)).toEqual(['はしを'])
    expect(convert('はしを', fake())[0]!.candidates.slice(0, 3)).toEqual(['箸を', '橋を', 'はしを'])
  })

  it('offers the hiragana near the top and the katakana last', () => {
    const { candidates } = convert('はし', fake())[0]!
    expect(candidates.indexOf('はし')).toBe(2)
    expect(candidates.at(-1)).toBe('ハシ')
  })

  it('favours common vocabulary through the bonus', () => {
    expect(convert('かんじ', fake())[0]!.candidates[0]).toBe('幹事')
    expect(convert('かんじ', fake({ 漢字: 300 }))[0]!.candidates[0]).toBe('漢字')
  })

  it('does not read kana as numerals', () => {
    expect(convert('ご', fake())[0]!.candidates[0]).toBe('語')
  })

  it('keeps characters no word starts with as typed', () => {
    expect(convert('はしx', fake()).map((p) => p.candidates[0]).join('')).toBe('箸x')
  })

  it('returns nothing for empty input', () => {
    expect(convert('', fake())).toEqual([])
  })
})

// The real dictionary is generated by `bun run reader:data`, which CI runs before the unit tests.
const DICT = 'public/reader/dict/'
const COMMON = 'public/reader/data/words-common.json'
describe.skipIf(!existsSync(`${DICT}base.dat.gz`) || !existsSync(COMMON))('convert with IPADIC', () => {
  let lexicon: Lexicon
  beforeAll(async () => {
    const tokenizer = await new Promise<kuromoji.Tokenizer<kuromoji.IpadicFeatures>>((resolve, reject) =>
      kuromoji.builder({ dicPath: DICT }).build((err, t) => (err ? reject(err) : resolve(t))),
    )
    lexicon = kuromojiLexicon(tokenizer, commonWords(JSON.parse(readFileSync(COMMON, 'utf8'))))
  }, 60_000)

  const best = (kana: string) => convert(kana, lexicon).map((p) => p.candidates[0]).join('|')

  it.each([
    ['わたしはにほんごがすきです', '私は|日本語が|好きです'],
    ['きのうとしょかんでほんをよみました', '昨日|図書館で|本を|読みました'],
    ['あしたはあめです', '明日は|雨です'],
    ['すしがたべたい', '寿司が|食べたい'],
    ['かんじをべんきょうしています', '漢字を|勉強しています'],
    ['にほんにいきたいです', '日本に|行きたいです'],
    ['でんしゃでがっこうにいきます', '電車で|学校に|行きます'],
    ['あたらしいくつをかいました', '新しい|靴を|買いました'],
    ['りんごをみっつください', 'りんごを|三つ|ください'],
    ['くつをはいてください', '靴を|履いてください'],
    ['らーめん', 'ラーメン'],
  ])('%s → %s', (kana, expected) => {
    expect(best(kana)).toBe(expected)
  })

  it('lists the other spellings of a phrase', () => {
    const [phrase] = convert('かんじを', lexicon)
    expect(phrase!.candidates).toEqual(expect.arrayContaining(['漢字を', '感じを', '幹事を', 'かんじを', 'カンジを']))
  })

  it('gives conjugated verbs the bonus of their dictionary form', () => {
    const verb = (surface: string, base: string): Entry => ({ surface, base, left: 0, right: 0, cost: 0, pos: '動詞', sub: '自立' })
    expect(lexicon.verbBonus!(verb('弾き', '弾く'), 'ひき')).toBeGreaterThan(0)
    // A potential verb (弾ける, can play) takes the bonus of the verb it is made from (弾く).
    expect(lexicon.verbBonus!(verb('弾け', '弾ける'), 'ひけ')).toBeGreaterThan(0)
    expect(lexicon.verbBonus!(verb('曳け', '曳ける'), 'ひけ')).toBe(0)
  })

  it.each(['ひきます', 'ひけます'])('offers common verbs before rare spellings for %s', (kana) => {
    const [phrase] = convert(kana, lexicon)
    expect(phrase!.candidates.slice(0, 2).map((c) => c[0]).sort()).toEqual(['弾', '引'].sort())
  })
})
