export type Sense = { pos: string[]; glosses: string[]; notes: string[] }
export type Word = {
  id: number
  kanji: string[]
  kana: string[]
  senses: Sense[]
  common: boolean
  jlpt: string
}
export type Kanji = {
  char: string
  meanings: string[]
  onyomi: string[]
  kunyomi: string[]
  strokeCount: number
  grade: number | null
  jlpt: string
}
export type Meta = { words: string; kanji: string }

/** [kanji, kana, senses, flags, jlpt, search-only spellings]; see scripts/build-data.mjs. */
export type RawWord = [string[], string[], [string[], string[], string[]][], number, string, string[]?]
type RawKanji = [string, string[], string[], string[], number, number | null, string]

// Generated by scripts/reader/build-data.mjs into public/reader/data.
const base = '/reader/'
const getJSON = async <T,>(file: string): Promise<T> => {
  const res = await fetch(`${base}data/${file}`)
  if (!res.ok) throw new Error(`Could not load ${file} (${res.status})`)
  return res.json()
}

const words: Word[] = []
const byForm = new Map<string, Word[]>()
const kanjiByChar = new Map<string, Kanji>()
let strokes: Promise<Record<string, string[]>> | undefined

/** Adds raw entries (the words-*.json format) to the index. Exported for tests. */
export function addWords(raw: RawWord[]) {
  for (const [kanji, kana, senses, flags, jlpt, hidden = []] of raw) {
    const word: Word = {
      id: words.length,
      kanji,
      kana,
      senses: senses.map(([pos, glosses, notes]) => ({ pos, glosses, notes })),
      common: (flags & 1) === 1,
      jlpt,
    }
    words.push(word)
    for (const form of new Set([...kanji, ...kana, ...hidden])) {
      const list = byForm.get(form)
      if (list) list.push(word)
      else byForm.set(form, [word])
    }
  }
}

// Loads are shared, so a second caller (React StrictMode runs effects twice in development) can't add every word twice.
let core: Promise<Meta> | undefined
let restCount: Promise<number> | undefined

/** Loads the common vocabulary and the kanji; resolves once lookups work. */
export function loadCore(): Promise<Meta> {
  core ??= loadCoreOnce().catch((e) => {
    core = undefined
    throw e
  })
  return core
}

async function loadCoreOnce(): Promise<Meta> {
  const [common, kanji, meta] = await Promise.all([
    getJSON<RawWord[]>('words-common.json'),
    getJSON<RawKanji[]>('kanji.json'),
    getJSON<Meta>('meta.json'),
  ])
  addWords(common)
  for (const [char, meanings, onyomi, kunyomi, strokeCount, grade, jlpt] of kanji) {
    kanjiByChar.set(char, { char, meanings, onyomi, kunyomi, strokeCount, grade, jlpt })
  }
  return meta
}

/** Loads the rest of JMdict (uncommon words); empty when only the common subset was built. */
export function loadRest(): Promise<number> {
  restCount ??= loadRestOnce().catch((e) => {
    restCount = undefined
    throw e
  })
  return restCount
}

async function loadRestOnce(): Promise<number> {
  const rest = await getJSON<RawWord[]>('words-rest.json')
  addWords(rest)
  return rest.length
}

export const lookup = (form: string): Word[] => byForm.get(form) ?? []
export const getKanji = (char: string): Kanji | undefined => kanjiByChar.get(char)
export const wordCount = () => words.length

export function getStrokes(char: string): Promise<string[] | undefined> {
  strokes ??= getJSON<Record<string, string[]>>('strokes.json')
  return strokes.then((s) => s[char])
}

/** Coarse word classes, used to match dictionary entries to the tokenizer's parts of speech. */
export type WordClass =
  | 'noun' | 'verb' | 'adjective' | 'adverb' | 'particle' | 'auxiliary' | 'conjunction'
  | 'interjection' | 'prenoun' | 'prefix' | 'suffix' | 'expression'

export function classesOf(word: Word): Set<WordClass> {
  const out = new Set<WordClass>()
  for (const s of word.senses) {
    for (const p of s.pos) {
      if (p.includes('auxiliary')) out.add('auxiliary')
      else if (p.includes('verb') && !p.startsWith('adverb')) out.add('verb')
      if (p === 'i-adjective' || p.startsWith('i-adjective')) out.add('adjective')
      if (/noun|numeric|counter|na-adjective|no-adjective|pronoun/.test(p) && !p.includes('pre-noun')) out.add('noun')
      if (p.startsWith('adverb')) out.add('adverb')
      if (p === 'particle') out.add('particle')
      if (p === 'conjunction') out.add('conjunction')
      if (p === 'interjection') out.add('interjection')
      if (p.startsWith('pre-noun')) out.add('prenoun')
      if (p.includes('prefix')) out.add('prefix')
      if (p.includes('suffix') || p === 'counter') out.add('suffix')
      if (p === 'expression') out.add('expression')
      if (p === 'copula') out.add('auxiliary')
    }
  }
  return out
}

/** Orders dictionary entries for a token: matching word class, then reading, then commonness. */
export function rankEntries(entries: Word[], wanted: { reading?: string; cls?: WordClass; form: string }): Word[] {
  const score = (w: Word) => {
    let s = 0
    if (wanted.cls && classesOf(w).has(wanted.cls)) s += 4
    if (wanted.reading && w.kana.includes(wanted.reading)) s += 3
    if (w.kanji.includes(wanted.form)) s += 1
    else if (w.kanji.length && w.senses.some((x) => x.notes.includes('usually kana'))) s += 1
    else if (!w.kanji.length) s += 1
    if (w.common) s += 1
    if (w.jlpt) s += 0.5
    return s
  }
  return entries
    .map((w) => [w, score(w)] as const)
    .sort((a, b) => b[1] - a[1] || a[0].id - b[0].id)
    .map(([w]) => w)
}

const normalizeGloss = (g: string) =>
  ` ${g.toLowerCase().replace(/\([^)]*\)/g, ' ').replace(/^\s*to\s+/, '').replace(/[^\p{L}\p{N}'-]+/gu, ' ').trim()} `

// Basic vocabulary first: an N5 word beats an N1 word with the same gloss.
const JLPT_BONUS: Record<string, number> = { N5: 10, N4: 8, N3: 6, N2: 4, N1: 2 }

/** English → Japanese search over the glosses. */
export function searchEnglish(query: string, limit = 40): Word[] {
  const q = normalizeGloss(query)
  if (q.trim().length < 2) return []
  const scored: [Word, number][] = []
  for (const w of words) {
    let best = 0
    w.senses.forEach((sense, si) => {
      sense.glosses.forEach((g, gi) => {
        const n = normalizeGloss(g)
        let s = 0
        if (n === q) s = 100
        else if (n.startsWith(q)) s = 60
        else if (n.includes(q)) s = 30
        if (s) best = Math.max(best, s - si * 6 - Math.min(gi * 0.3, 1.5))
      })
    })
    if (best > 0) scored.push([w, best + (w.common ? 12 : 0) + (JLPT_BONUS[w.jlpt] ?? 0)])
  }
  return scored
    .sort((a, b) => b[1] - a[1] || a[0].id - b[0].id)
    .slice(0, limit)
    .map(([w]) => w)
}

/** Words written with a kanji, common and JLPT-listed first. */
export function wordsWithKanji(char: string, limit = 12): Word[] {
  const found: Word[] = []
  for (const w of words) if (w.kanji.some((k) => k.includes(char))) found.push(w)
  const rank = (w: Word) => (w.common ? 0 : 2) + (w.jlpt ? 0 : 1) + (w.kanji[0]?.length ?? 0) / 10
  return found.sort((a, b) => rank(a) - rank(b) || a.id - b.id).slice(0, limit)
}
