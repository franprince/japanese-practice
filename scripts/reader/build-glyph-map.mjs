// Builds src/features/reader/lib/glyph-map.ts: Chinese-only glyphs → the Japanese kanji they stand for.
//
// Lyrics from Chinese sources (NetEase) often write a Japanese song with Chinese glyphs: 步 for 歩, 场 for 場.
// The tokenizer only knows the Japanese ones, so 步いてたら falls apart into 步 + いてたら.
//
// A character is mapped only when it is outside JIS X 0208 (the Japanese character set) and its
// replacement is inside it, so kanji Japanese also uses (叶, 后, 芸) are never touched. Candidates, in order:
//   1. Unihan kJapaneseNewVariant              步 → 歩
//   2. OpenCC simplified → traditional, then traditional → shinjitai   发 → 發 → 発
//   3. Unihan traditional, Z and semantic variants (then → shinjitai)   塲 → 場
//
// Run once and commit the result: `node scripts/reader/build-glyph-map.mjs`. Needs network access and `unzip`.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const OPENCC = 'https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary'
const UNIHAN = 'https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip'
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../src/features/reader/lib/glyph-map.ts')

const range = (from, to) => Array.from({ length: to - from + 1 }, (_, i) => from + i)

async function text(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url} answered ${res.status}`)
  return res.text()
}

/** OpenCC's `key<TAB>value value…` lines, single characters only. */
async function opencc(name) {
  const rows = []
  for (const line of (await text(`${OPENCC}/${name}.txt`)).split('\n')) {
    if (!line || line.startsWith('#')) continue
    const [key, values = ''] = line.split('\t')
    const list = values.split(' ').filter((v) => [...v].length === 1)
    if ([...key].length === 1 && list.length) rows.push([key, list])
  }
  return rows
}

async function unihanVariants() {
  const dir = mkdtempSync(join(tmpdir(), 'unihan-'))
  const zip = join(dir, 'Unihan.zip')
  const res = await fetch(UNIHAN)
  if (!res.ok) throw new Error(`${UNIHAN} answered ${res.status}`)
  writeFileSync(zip, Buffer.from(await res.arrayBuffer()))
  const raw = execFileSync('unzip', ['-p', zip, 'Unihan_Variants.txt'], { maxBuffer: 1 << 28 }).toString()
  const fields = new Map()
  const char = (code) => String.fromCodePoint(parseInt(code.slice(2), 16))
  for (const line of raw.split('\n')) {
    if (!line.startsWith('U+')) continue
    const [code, field, values] = line.split('\t')
    const key = `${char(code)}\t${field}`
    fields.set(key, values.split(' ').map((v) => char(v.split('<')[0])))
  }
  return (c, field) => fields.get(`${c}\t${field}`) ?? []
}

/**
 * JIS X 0208, the kanji a Japanese text is expected to use. Browsers decode Shift_JIS as Windows-31J,
 * so only its JIS X 0208 lead bytes are read: the NEC and IBM extensions (塲, 髙) get mapped too.
 */
function jisKanji() {
  const decoder = new TextDecoder('shift_jis')
  const set = new Set()
  const leads = [...range(0x88, 0x9f), ...range(0xe0, 0xea)]
  for (const lead of leads) {
    for (let trail = 0x40; trail <= 0xfc; trail++) {
      const c = decoder.decode(new Uint8Array([lead, trail]))
      if ([...c].length === 1 && /\p{Script=Han}/u.test(c)) set.add(c)
    }
  }
  return set
}

const [stRows, shinjitaiRows, variants] = await Promise.all([
  opencc('STCharacters'),
  opencc('JPShinjitaiCharacters'),
  unihanVariants(),
])
const jis = jisKanji()
// Simplified → its first traditional form.
const st = new Map(stRows.map(([s, [t]]) => [s, t]))
// JPShinjitaiCharacters maps shinjitai → kyujitai; read it backwards.
const shinjitai = new Map()
for (const [shin, kyu] of shinjitaiRows) for (const k of kyu) if (k !== shin && !shinjitai.has(k)) shinjitai.set(k, shin)
const toShinjitai = (c) => shinjitai.get(c) ?? c

function japaneseFor(c) {
  const japanese = (v) => (v && v !== c && jis.has(v) ? v : undefined)
  const direct = japanese(variants(c, 'kJapaneseNewVariant')[0]) ?? japanese(st.get(c) && toShinjitai(st.get(c)))
  if (direct) return direct
  // A variant field may list several kanji (﨑 → 埼 崎 嵜…); only an unambiguous one is safe to use.
  for (const field of ['kTraditionalVariant', 'kZVariant', 'kSemanticVariant', 'kSpecializedSemanticVariant']) {
    const found = new Set(variants(c, field).map(toShinjitai).filter(japanese))
    if (found.size === 1) return [...found][0]
    if (found.size > 1) return undefined
  }
  return undefined
}

const pairs = []
for (let cp = 0x3400; cp <= 0x3ffff; cp++) {
  const c = String.fromCodePoint(cp)
  if (jis.has(c) || !/\p{Script=Han}/u.test(c)) continue
  const ja = japaneseFor(c)
  if (ja) pairs.push(c + ja)
}

writeFileSync(
  OUT,
  `// Generated by scripts/reader/build-glyph-map.mjs from Unihan (Unicode License v3) and OpenCC (Apache-2.0); do not edit.
// Pairs of [Chinese-only glyph, Japanese kanji], for characters outside JIS X 0208.
export const GLYPH_PAIRS = ${JSON.stringify(pairs.join(''))}
`,
)
console.log(`${pairs.length} glyphs → ${OUT}`)
